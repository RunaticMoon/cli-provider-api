def test_gateway_mode_requires_control_base_url(tmp_path):
    """A gateway-mode execution target without a separate control target
    fails policy validation."""
    from cli_provider_kanban.policy import load_policy

    data = policy_dict()
    data["execution"] = {"mode": "gateway",
                         "base_url": "http://127.0.0.1:9"}
    path = write_policy(tmp_path, data)
    with pytest.raises(Exception):
        load_policy(path)


def test_gateway_submit_uses_route_combo(board, tmp_path, dispatch_policy):
    """Gateway mode must send the classifier route-derived combo name, never
    a static execution.model that bypasses classification."""
    db, bridge = board
    data, rev = dispatch_policy
    data["execution"] = {
        "mode": "gateway",
        "base_url": "http://127.0.0.1:9",
        "control_base_url": "http://127.0.0.1:9",
    }
    data["workspaces"]["ws-main"]["runner_execution_config"] = str(
        write_runner_config(
            tmp_path / "cfg5" / "exec.json",
            {"ws-alpha": {
                "root": data["workspaces"]["ws-main"]["prepared_worktree"],
                "allowed_actions": [],
                "allowed_presets": ["jev.worker.code.standard"],
                "allowed_models": None,
            }},
        )
    )
    tid = _card(bridge, tmp_path, data, rev)
    client = FakeWrapper()
    report, _ = _run(db, tmp_path, data, client)
    rec = _result(report, tid)
    assert rec["action"] == "review", rec
    assert client.calls[0]["model"] == "jev.worker.code.standard"
