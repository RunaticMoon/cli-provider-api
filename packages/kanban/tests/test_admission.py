def test_prepared_worktree_at_wrong_revision_refused(
    board, tmp_path, dispatch_policy
):
    db, bridge = board
    data, rev = dispatch_policy
    ws = data["workspaces"]["ws-main"]
    repo = ws["repo"]
    # Advance the repo and prepare a worktree at the NEW commit while the
    # card pins the OLD base -> HEAD != base must refuse.
    env = dict(os.environ, GIT_AUTHOR_NAME="t", GIT_AUTHOR_EMAIL="t@t",
               GIT_COMMITTER_NAME="t", GIT_COMMITTER_EMAIL="t@t")
    Path(repo, "later.txt").write_text("later\n")
    subprocess.run(["git", "add", "-A"], cwd=repo, env=env, check=True,
                   capture_output=True)
    subprocess.run(["git", "commit", "-qm", "later"], cwd=repo, env=env,
                   check=True, capture_output=True)
    newer = subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=repo, env=env, check=True,
        capture_output=True, text=True).stdout.strip()
    # Re-point the prepared worktree at the wrong commit.
    subprocess.run(["git", "checkout", "-q", newer], cwd=ws["prepared_worktree"],
                   env=env, check=True, capture_output=True)
    tid = _card(bridge, tmp_path, data, rev)
    client = FakeWrapper()
    report, _ = _run(db, tmp_path, data, client)
    rec = _result(report, tid)
    assert rec["action"] == "blocked"
    assert client.calls == []


