def test_prepared_worktree_foreign_repo_refused(
    board, tmp_path, dispatch_policy, git_repo
):
    db, bridge = board
    data, rev = dispatch_policy
    repo, _rev = git_repo
    # A git worktree of a DIFFERENT repository at the same base is foreign.
    other = tmp_path / "other-repo"
    subprocess.run(["git", "init", "-q", str(other)], check=True,
                   capture_output=True)
    env = dict(os.environ, GIT_AUTHOR_NAME="t", GIT_AUTHOR_EMAIL="t@t",
               GIT_COMMITTER_NAME="t", GIT_COMMITTER_EMAIL="t@t")
    Path(other, "x.txt").write_text("x\n")
    subprocess.run(["git", "add", "-A"], cwd=other, env=env, check=True,
                   capture_output=True)
    subprocess.run(["git", "commit", "-qm", "x"], cwd=other, env=env,
                   check=True, capture_output=True)
    foreign = tmp_path / "foreign-wt"
    subprocess.run(
        ["git", "worktree", "add", "--quiet", "--detach", str(foreign), rev],
        cwd=other, env=env, check=False, capture_output=True,
    )
    ws = data["workspaces"]["ws-main"]
    ws["prepared_worktree"] = str(foreign)
    tid = _card(bridge, tmp_path, data, rev)
    client = FakeWrapper()
    report, _ = _run(db, tmp_path, data, client)
    rec = _result(report, tid)
    assert rec["action"] == "blocked"
    assert client.calls == []


